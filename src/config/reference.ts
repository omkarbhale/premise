import { describeCheck } from "./checks.js";
import { CONFIG_FILE_NAME, DATA_FOLDER_ENV, envNameFor } from "./load.js";
import { AGENT_TASK_KINDS, SETTINGS, type Setting } from "./settings.js";

function cell(value: string): string {
  return value.replace(/\|/g, "\\|");
}

function recordLink(record: string | undefined): string {
  if (!record) return "";
  return `[${record}](../decisions/README.md)`;
}

function row(s: Setting): string {
  return `| \`${s.key}\` | \`${JSON.stringify(s.default)}\` | ${cell(describeCheck(s.check))} | ${cell(s.meaning)} | ${recordLink(s.record)} |`;
}

/** The configuration reference page, generated from the settings list. */
export function configurationReference(): string {
  const general = SETTINGS.filter((s) => !s.key.startsWith("agents.tasks."));
  const tasks = SETTINGS.filter((s) => s.key.startsWith("agents.tasks."));
  const header = [
    "| Setting | Default | Allowed | Meaning | Record |",
    "| --- | --- | --- | --- | --- |",
  ];
  return [
    "# Configuration reference",
    "",
    "<!-- Generated by `npm run docs:config` from src/config/settings.ts. Do not edit by hand; a test checks it. -->",
    "",
    "Every setting has a default, so premise runs with no configuration at all. Change a setting in one of two ways:",
    "",
    `- **The settings file:** \`${CONFIG_FILE_NAME}\` in the data folder, one JSON object. A dotted key is a nested object: \`queue.max_agent_sessions\` is \`{ "queue": { "max_agent_sessions": 3 } }\`.`,
    `- **An environment variable:** \`PREMISE_\` and the key in capitals, each dot as a double underscore: \`${envNameFor("queue.max_agent_sessions")}=3\`. Environment variables win over the file.`,
    "",
    `The data folder itself is set by \`--data <folder>\`, then \`${DATA_FOLDER_ENV}\`, then \`.premise\` in your home folder, because the settings file lives inside it.`,
    "",
    "A wrong setting stops premise at start with a message naming the setting and why. `premise doctor` checks the settings without starting anything.",
    "",
    "## General",
    "",
    ...header,
    ...general.map(row),
    "",
    "## Per type of task",
    "",
    `Each type of agent task has its own model, effort and limits. The types are: ${AGENT_TASK_KINDS.join(", ")}.`,
    "",
    ...header,
    ...tasks.map(row),
    "",
  ].join("\n");
}
